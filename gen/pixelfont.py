GLYPH_W, GLYPH_H, ADVANCE = 5, 7, 6


def text_width(text: str, scale: int) -> int:
    return (len(text) * ADVANCE - 1) * scale if text else 0


def text_path(text: str, x: float, y: float, scale: int) -> str:
    """Retorna o atributo d de um <path> com os pixels do texto.

    Pixels vizinhos na mesma linha viram um único retângulo para manter o SVG enxuto.
    """
    parts = []
    for i, ch in enumerate(text.upper()):
        glyph = GLYPHS.get(ch)
        if glyph is None:
            raise KeyError(f"glifo ausente: {ch!r}")
        gx = x + i * ADVANCE * scale
        for row, line in enumerate(glyph):
            col = 0
            while col < GLYPH_W:
                if line[col] == "#":
                    start = col
                    while col < GLYPH_W and line[col] == "#":
                        col += 1
                    w = (col - start) * scale
                    px = gx + start * scale
                    py = y + row * scale
                    parts.append(f"M{px:g} {py:g}h{w:g}v{scale:g}h{-w:g}z")
                else:
                    col += 1
    return "".join(parts)


def sprite_path(rows: list[str], x: float, y: float, scale: int, char: str) -> str:
    """Pixels de um sprite (linhas de caracteres) que batem com `char`."""
    parts = []
    for r, line in enumerate(rows):
        c = 0
        while c < len(line):
            if line[c] == char:
                s = c
                while c < len(line) and line[c] == char:
                    c += 1
                w = (c - s) * scale
                parts.append(f"M{x + s * scale:g} {y + r * scale:g}h{w:g}v{scale:g}h{-w:g}z")
            else:
                c += 1
    return "".join(parts)
